const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'source/faq');
const upstream = JSON.parse(fs.readFileSync(path.join(dir, 'upstream.json'), 'utf8'));
const titles = JSON.parse(fs.readFileSync(path.join(dir, 'sections-zh.json'), 'utf8'));
const zh = {};
for (const file of ['zh-01.json', 'zh-02.json', 'zh-03.json']) {
  for (const [id, value] of Object.entries(JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')))) {
    if (zh[id]) throw Error(`Duplicate translation: ${id}`);
    zh[id] = value;
  }
}
if (titles.length !== upstream.sections.length || Object.keys(zh).length !== upstream.entries.length) throw Error('Translation coverage differs from pinned source');
const groups = [
  [0, '基础规则', '核心规则书'], [26, '天赋', '核心规则书'], [34, '标签与通用装备', '核心规则书'],
  [47, '核心厂商牌照', '核心规则书'], [73, '漫长边缘 · Long Rim', '漫长边缘（Long Rim）'],
  [76, '不当壁花 · 第一部', '不当壁花第一部（No Room for a Wallflower, Part 1）'],
  [79, '卡拉金贸易男爵国', '卡拉金贸易男爵国（Karrakin Trade Baronies）'],
  [84, '至日之雨 · Solstice Rain', '至日之雨（Solstice Rain）'],
  [87, '海妖之歌，山峦之悔', '海妖之歌，山峦之悔（Siren’s Song, A Mountain’s Remorse）'],
  [89, '冬日之痕 · Winter Scar', '冬日之痕（Winter Scar）'],
  [93, 'NPC 与模板', '核心规则书'], [112, '跨牌照互动', '跨牌照互动']
];
const sections = upstream.sections.map((s, i) => {
  const group = groups.filter(g => g[0] <= i).at(-1);
  const page = s.title.match(/(?:Page |Part 1 )(\d+)/)?.[1] || '';
  return { ...s, en: s.title, title: titles[i], group: group[1], book: group[2], page };
});
const entries = upstream.entries.map(e => {
  if (!zh[e.id] || zh[e.id].length !== 2 || zh[e.id].some(t => !t.trim())) throw Error(`Missing translation: ${e.id}`);
  const sources = [...e.answer.matchAll(/<wot:(\d+\/\d+)>/g)].map(m => `https://discord.com/channels/426286410496999425/${m[1]}`);
  const [question, answer] = zh[e.id];
  return { id: e.id, section: e.section, question, answer, enQuestion: e.question, enAnswer: e.answer.replace(/<wot:[^>]+>/g, '').trim(), sources, errata: /Errata\?/.test(e.question) };
});
const data = { ...upstream, title: 'LANCER 规则 FAQ 与勘误', sections, entries };
fs.writeFileSync(path.join(root, 'faq-data.js'), '// Generated by tools/build-faq.js. FAQ translation: GPL-3.0; source/faq/LICENSE.\nwindow.LANCER_FAQ = ' + JSON.stringify(data) + ';\n');
console.log(`FAQ: ${entries.length}/${upstream.entries.length} translated, ${sections.length} sections, ${entries.reduce((n,e)=>n+e.sources.length,0)} ruling links preserved.`);
