const fs=require('fs'),path=require('path'),vm=require('vm');
function buildEquipmentLore(root=path.join(__dirname,'..')) {
 const ctx={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'assets/js/data.js'),'utf8'),ctx);const d=ctx.window.LANCER_DATA;
 const zh=JSON.parse(fs.readFileSync(path.join(root,'source/lore/zh.json'),'utf8'));
 const out={},missing=[],english=[],counts={zh:0,en:0,missing:0};
 const normalize=require('./core-v35').translator(require('./core-v35').spec.terms.map(t=>[t.from,t.to]));
 for(const kind of ['weapons','systems','mods']) {
  const raw=JSON.parse(fs.readFileSync(path.join(root,'source/lancer-data',kind+'.json'),'utf8'));
  const originals=Object.fromEntries(raw.map(x=>[x.id,x.description]));
  for(const it of d[kind]) {
   const found=zh[it.id],existing=it.description;
   const rawText=existing||originals[it.id]||'';
   const text=found?.text||(/^Gained from\b/.test(rawText)?'':rawText);
   const name=it.zh_name||it.name,lang=/[\u4e00-\u9fff]/.test(text)?'zh':'en';
   const row={id:it.id,name,kind,license:it.license||'内建／天赋',pack:it.pack||'核心规则书'};
   if(text.trim()) {
    out[it.id]={text:normalize(text),lang,source:found?.source||(it.ext?'项目已录入资料':'COMP/CON 原始数据'),pages:found?.pages||[]};counts[lang]++;
    if(lang==='en')english.push(row);
   } else {missing.push(row);counts.missing++;}
  }
 }
 fs.mkdirSync(path.join(root,'assets/js'),{recursive:true});
 fs.writeFileSync(path.join(root,'assets/js/equipment-lore.js'),'// Generated by tools/build-equipment-lore.js\nwindow.LANCER_LORE = '+JSON.stringify({items:out,counts})+';\n');
 const lines=['# 武器、系统与改装风味文本核对','','[文档目录](README.md) · [项目说明](../README.md) · [风味文本维护](../source/lore/README.md)','','本表由 `node tools/build-equipment-lore.js` 根据当前本地数据生成。请修改源数据后重新构建，不直接编辑本表；生成日期不代表已同步上游最新资料。','',`已补中文 ${counts.zh} 项；仅有英文原文 ${counts.en} 项；尚未可靠匹配独立风味文本 ${counts.missing} 项。`,'','缺项可能是原书没有独立段落，也可能是名称或排版差异导致未能可靠匹配，需按条目进一步核对。GMS武器沿用上游提供的系列共用介绍；天赋装备的获取说明不作为风味文本，也未用规则效果或牌照总介绍代替缺失段落。',''];
 for(const [title,rows] of [['仅有英文原文，待补中文',english],['当前资料未找到独立风味文本',missing]]) {
  lines.push('## '+title,'','| 类型 | 名称 | 牌照／来源 | ID |','|---|---|---|---|');
  for(const r of rows)lines.push(`| ${{weapons:'武器',systems:'系统',mods:'改装'}[r.kind]} | ${r.name} | ${r.license} · ${r.pack} | ${r.id} |`);
  lines.push('');
 }
 fs.mkdirSync(path.join(root,'docs'),{recursive:true});
 fs.writeFileSync(path.join(root,'docs','EQUIPMENT-LORE-AUDIT.md'),lines.join('\n'));
 console.log('Equipment lore:',JSON.stringify(counts));return counts;
}
module.exports=buildEquipmentLore;
if(require.main===module)buildEquipmentLore();
